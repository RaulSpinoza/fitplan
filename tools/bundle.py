#!/usr/bin/env python3
"""FitPlan source bundle tool (stdlib only).

  python tools/bundle.py make              -> writes fitplan-source.txt + version.json
  python tools/bundle.py verify BUNDLE     -> checks every file's SHA-256
  python tools/bundle.py unpack BUNDLE DIR -> recreates the source tree in DIR (verified)
  python tools/bundle.py selftest          -> bundle round-trip equals the working tree

Bundle format (fitplan.bundle/1), one block per file:
  #@FITPLAN-BUNDLE v1 version=<app version> commit=<git sha> files=<n>
  #@FILE path=<path> enc=<utf8|base64> bytes=<n> sha256=<hex>
  <content>
  #@END path=<path>
Text files are stored verbatim (readable), binary files as base64.
"""
import base64, hashlib, json, os, re, subprocess, sys, datetime

BUNDLE, MANIFEST = 'fitplan-source.txt', 'version.json'
EXCLUDE_FILES = {BUNDLE, MANIFEST}
EXCLUDE_DIRS = {'.git', 'node_modules', 'samples', 'data', 'backups'}
# never bundle personal training data, even if committed by mistake
EXCLUDE_RE = re.compile(r'(\.fit$|\.fit\.txt$|^fitplan-backup-.*\.json$|^progress.*\.(json|md)$|\.DS_Store$)', re.I)
TEXT_EXT = {'.html', '.css', '.js', '.mjs', '.json', '.md', '.txt', '.yml', '.yaml', '.py', '.svg', '.webmanifest', ''}
HDR = re.compile(r'^#@FILE path=(\S+) enc=(utf8|base64) bytes=(\d+) sha256=([0-9a-f]{64})$')

sha = lambda b: hashlib.sha256(b).hexdigest()

def git(*a):
    try: return subprocess.check_output(['git', *a], stderr=subprocess.DEVNULL).decode().strip()
    except Exception: return ''

def source_files(root='.'):
    listed = git('ls-files')
    paths = listed.splitlines() if listed else [
        os.path.relpath(os.path.join(d, f), root).replace(os.sep, '/')
        for d, ds, fs in os.walk(root) if not ds.__setitem__(slice(None), [x for x in ds if x not in EXCLUDE_DIRS]) for f in fs]
    out = []
    for p in sorted(set(paths)):
        parts = p.split('/')
        if p in EXCLUDE_FILES or EXCLUDE_DIRS & set(parts[:-1]) or EXCLUDE_RE.search(parts[-1]) or not os.path.isfile(p): continue
        out.append(p)
    return out

def is_text(path, data):
    if os.path.splitext(path)[1].lower() not in TEXT_EXT: return False
    try: data.decode('utf-8'); return b'\x00' not in data
    except UnicodeDecodeError: return False

def app_version():
    try:
        m = re.search(r"VERSION\s*=\s*'fitplan-([^']+)'", open('sw.js', encoding='utf-8').read())
        return m.group(1) if m else 'unknown'
    except OSError: return 'unknown'

def make():
    files, blocks, manifest = source_files(), [], {}
    ver, commit = app_version(), git('rev-parse', 'HEAD') or 'local'
    for p in files:
        data = open(p, 'rb').read()
        text = is_text(p, data)
        body = data.decode('utf-8') if text else base64.encodebytes(data).decode('ascii')
        if not body.endswith('\n'): body += '\n'           # block separator; exact length is in bytes=
        blocks.append(f'#@FILE path={p} enc={"utf8" if text else "base64"} bytes={len(data)} sha256={sha(data)}\n{body}#@END path={p}\n')
        manifest[p] = {'sha256': sha(data), 'bytes': len(data)}
    head = (f'#@FITPLAN-BUNDLE v1 version={ver} commit={commit} files={len(files)}\n'
            f'# Generated by tools/bundle.py. Restore with: python tools/bundle.py unpack {BUNDLE} <dir>\n')
    with open(BUNDLE, 'w', encoding='utf-8', newline='\n') as f: f.write(head + ''.join(blocks))
    with open(MANIFEST, 'w', encoding='utf-8', newline='\n') as f:
        json.dump({'app': 'FitPlan', 'version': ver, 'source_commit': commit,
                   'generated_at': datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'),
                   'bundle_sha256': sha(open(BUNDLE, 'rb').read()), 'files': manifest}, f, indent=2)
        f.write('\n')
    print(f'{BUNDLE}: {len(files)} files, version {ver}, commit {commit[:7]}')

def parse(bundle_path):
    raw = open(bundle_path, 'rb').read()
    text = raw.decode('utf-8-sig')
    if not text.startswith('#@FITPLAN-BUNDLE v1'): raise SystemExit('Not a FitPlan bundle (missing #@FITPLAN-BUNDLE v1 header)')
    lines, i, files = text.split('\n'), 0, []
    while i < len(lines):
        m = HDR.match(lines[i].rstrip('\r'))
        if not m: i += 1; continue
        path, enc, n, h = m.group(1), m.group(2), int(m.group(3)), m.group(4)
        j = i + 1
        while j < len(lines) and lines[j].rstrip('\r') != f'#@END path={path}': j += 1
        if j == len(lines): raise SystemExit(f'Truncated bundle: no #@END for {path}')
        body = '\n'.join(lines[i + 1:j])
        if enc == 'base64': data = base64.b64decode(re.sub(r'[^A-Za-z0-9+/=]', '', body))
        else:
            data = (body + '\n').encode('utf-8')[:n]
            if sha(data) != h:                                   # tolerate CRLF conversion during download
                alt = ('\n'.join(l[:-1] if l.endswith('\r') else l for l in body.split('\n')) + '\n').encode('utf-8')[:n]
                data = alt if sha(alt) == h else data
        files.append((path, data, h, n)); i = j + 1
    return text.split('\n', 1)[0], files

def verify(bundle_path, quiet=False):
    head, files = parse(bundle_path)
    bad = [p for p, d, h, n in files if sha(d) != h or len(d) != n]
    if not quiet:
        print(head)
        for p, d, h, n in files: print(f"{'OK ' if p not in bad else 'BAD'} {p} ({n} bytes)")
    print(f'{len(files) - len(bad)}/{len(files)} files verified' + ('' if not bad else f' – MISMATCH: {", ".join(bad)}'))
    return files, bad

def unpack(bundle_path, dest):
    files, bad = verify(bundle_path, quiet=True)
    if bad: raise SystemExit('Aborted: checksum mismatch, nothing written.')
    for p, d, h, n in files:
        if p.startswith('/') or '..' in p.split('/'): raise SystemExit(f'Unsafe path in bundle: {p}')
        out = os.path.join(dest, *p.split('/'))
        os.makedirs(os.path.dirname(out) or '.', exist_ok=True)
        with open(out, 'wb') as f: f.write(d)
    print(f'Unpacked {len(files)} files to {dest}')

def selftest():
    files, bad = verify(BUNDLE, quiet=True)
    got, want = {p: d for p, d, h, n in files}, source_files()
    diff = [p for p in want if got.get(p) != open(p, 'rb').read()] + [p for p in got if p not in want]
    if bad or diff: raise SystemExit(f'Self-test FAILED: {", ".join(bad + diff)}')
    print(f'Self-test OK: {len(want)} files round-trip byte-exact')

if __name__ == '__main__':
    a = sys.argv[1:]
    if a[:1] == ['make']: make()
    elif a[:1] == ['verify'] and len(a) == 2: sys.exit(1 if verify(a[1])[1] else 0)
    elif a[:1] == ['unpack'] and len(a) == 3: unpack(a[1], a[2])
    elif a[:1] == ['selftest']: selftest()
    else: print(__doc__); sys.exit(2)
